// Subsets the Bootstrap Icons font to the icons this site actually uses.
//
// The full font has 2,000+ glyphs (about 134 KiB as woff2), and the site uses about 40.
// This script scans the source and db.json for `bi-<name>` classes, then writes:
//   src/generated/icons.woff2  - only those glyphs
//   src/generated/icons.css    - @font-face and one rule per used icon
// It runs automatically before `npm run dev` and `npm run build`. Scanning is
// O(source size), and looking up each icon's codepoint is O(1).
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const out = join(root, 'src', 'generated');

export const ICON_RE = /\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g;

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'generated' || name === 'test') continue;
    if (statSync(p).isDirectory()) yield* files(p);
    else if (/\.(jsx?|html)$/.test(name)) yield p;
  }
}

export function usedIcons() {
  const sources = [...files(join(root, 'src')), join(root, 'index.html'), resolve(root, '..', 'db.json')];
  const names = new Set();
  for (const f of sources) for (const m of readFileSync(f, 'utf8').matchAll(ICON_RE)) names.add(m[1]);
  return [...names].sort();
}

export async function buildIcons() {
  const codepoints = require('bootstrap-icons/font/bootstrap-icons.json');
  const names = usedIcons();
  const unknown = names.filter((n) => !(n in codepoints));
  if (unknown.length) throw new Error(`unknown Bootstrap Icons: ${unknown.join(', ')}`);

  const full = readFileSync(require.resolve('bootstrap-icons/font/fonts/bootstrap-icons.woff2'));
  const text = names.map((n) => String.fromCodePoint(codepoints[n])).join('');
  const subset = await subsetFont(full, text, { targetFormat: 'woff2' });

  const rules = names
    .map((n) => `.bi-${n}::before{content:"\\${codepoints[n].toString(16)}"}`)
    .join('\n');
  const css = `/* Generated by scripts/build-icons.mjs: ${names.length} icons. Do not edit. */
@font-face{font-family:"bootstrap-icons";font-display:block;src:url("./icons.woff2") format("woff2")}
.bi::before,[class^="bi-"]::before,[class*=" bi-"]::before{display:inline-block;font-family:bootstrap-icons!important;font-style:normal;font-weight:normal!important;font-variant:normal;text-transform:none;line-height:1;vertical-align:-.125em;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}
${rules}
`;
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'icons.woff2'), subset);
  writeFileSync(join(out, 'icons.css'), css);
  return { count: names.length, fullBytes: full.length, subsetBytes: subset.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await buildIcons();
  console.log(
    `icons: ${r.count} used; font ${(r.fullBytes / 1024).toFixed(1)} KiB -> ${(r.subsetBytes / 1024).toFixed(1)} KiB`,
  );
}
